namespace Tracker.Search;

// Common Bulgarian nicknames and the official names behind them. Covers what
// the local model gets wrong (it does not know that Митко is Димитър).
public static class NicknameDictionary
{
    public const int MaxExpansions = 8;

    // Keys and values are in NameNormalizer form (lower case Cyrillic).
    private static readonly Dictionary<string, string[]> Nicknames = new()
    {
        // Male
        ["ваньо"] = ["иван"], ["ванката"] = ["иван"], ["ванко"] = ["иван"],
        ["гошо"] = ["георги"], ["жоро"] = ["георги"], ["гошко"] = ["георги"],
        ["митко"] = ["димитър"], ["митьо"] = ["димитър"], ["мите"] = ["димитър"], ["димо"] = ["димитър"],
        ["пешо"] = ["петър"], ["петьо"] = ["петър"], ["пепи"] = ["петър", "петя"],
        ["тошко"] = ["тодор"], ["тошо"] = ["тодор"], ["тошето"] = ["тодор"],
        ["сашо"] = ["александър", "александра"], ["сашко"] = ["александър"], ["алекс"] = ["александър"],
        ["стефчо"] = ["стефан"], ["стефо"] = ["стефан"],
        ["ники"] = ["николай", "никола", "николета"], ["нико"] = ["николай", "никола"], ["кольо"] = ["николай"],
        ["краси"] = ["красимир", "красимира"],
        ["любо"] = ["любомир"], ["любчо"] = ["любомир"],
        ["кальо"] = ["калоян"], ["калчо"] = ["калоян"],
        ["боби"] = ["борислав", "борис", "боряна"], ["бобо"] = ["борислав", "борис"],
        ["цецо"] = ["цветан", "цветомир"],
        ["ицо"] = ["христо"], ["ичо"] = ["христо"],
        ["васко"] = ["васил"], ["вальо"] = ["валентин"],
        ["наско"] = ["атанас"], ["насо"] = ["атанас"],
        ["мишо"] = ["михаил"], ["емо"] = ["емил"],
        ["радо"] = ["радослав", "радостин"],
        ["кико"] = ["кирил"], ["киро"] = ["кирил"],
        ["венци"] = ["венцислав"], ["пламчо"] = ["пламен"],
        ["данчо"] = ["йордан", "даниел"], ["дачо"] = ["йордан"],
        ["стойчо"] = ["стоян"], ["марто"] = ["мартин"], ["крис"] = ["кристиан", "кристина"],
        ["вили"] = ["виктор", "вилиана"], ["ико"] = ["ивайло"], ["ивчо"] = ["ивайло"],
        ["симо"] = ["симеон"], ["мони"] = ["симеон", "моника", "симона"],
        ["ангелчо"] = ["ангел"], ["слави"] = ["славчо", "славена"],

        // Female
        ["мими"] = ["мария"], ["мария"] = ["мария"], ["мара"] = ["мария"], ["мимето"] = ["мария"],
        ["ани"] = ["анна", "ана"], ["анче"] = ["анна", "ана"],
        ["ели"] = ["елена", "елица", "елисавета"], ["елка"] = ["елена"],
        ["габи"] = ["габриела"], ["деси"] = ["десислава"],
        ["вики"] = ["виктория"], ["цвети"] = ["цветелина", "цветанка"],
        ["ради"] = ["радослава", "радостина"], ["гери"] = ["гергана"],
        ["дани"] = ["даниела"], ["кристи"] = ["кристина"],
        ["поли"] = ["полина"], ["роси"] = ["росица"],
        ["таня"] = ["татяна"], ["теди"] = ["теодора"], ["надя"] = ["надежда"],
        ["веси"] = ["веселина"], ["стефи"] = ["стефания"], ["бети"] = ["елизабет"],
        ["мили"] = ["милена"], ["йоани"] = ["йоана"], ["жени"] = ["евгения"],
        ["люба"] = ["любов", "любомира"], ["диди"] = ["диана"], ["ина"] = ["ирина"]
    };

    // Every reading of the query with its nicknames replaced by official names,
    // e.g. "Митко Стоянов" -> ["димитър стоянов"]. Empty if the query has no
    // known nickname.
    public static IReadOnlyList<string> Expand(string query)
    {
        var words = NameNormalizer.Normalize(query)
            .Split(' ', StringSplitOptions.RemoveEmptyEntries);

        if (!words.Any(w => Nicknames.ContainsKey(w)))
        {
            return [];
        }

        IEnumerable<string> readings = [""];

        foreach (var word in words)
        {
            var options = Nicknames.GetValueOrDefault(word, [word]);
            readings = readings
                .SelectMany(prefix => options.Select(o => prefix.Length == 0 ? o : $"{prefix} {o}"))
                .Take(MaxExpansions);
        }

        return readings.ToList();
    }
}
